// Overwrites src/embedded-posthog-key.ts with a real PostHog project key so
// release builds ship telemetry enabled. Source checkouts keep the undefined
// placeholder. Run before `pnpm --filter @dev.fast/review build`.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const key = (process.env.REVIEW_POSTHOG_KEY ?? process.argv[2] ?? "").trim();
if (!key) {
  console.error(
    "embed-posthog-key: set REVIEW_POSTHOG_KEY or pass the key as an argument",
  );
  process.exit(1);
}
if (!/^phc_[A-Za-z0-9]+$/.test(key)) {
  console.error("embed-posthog-key: value does not look like a PostHog key");
  process.exit(1);
}

const target = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "embedded-posthog-key.ts",
);
writeFileSync(
  target,
  [
    "// Generated by scripts/embed-posthog-key.mjs for a release build.",
    "// Do not commit a real key: source checkouts keep this undefined.",
    "export const EMBEDDED_PROGRESSIVE_REVIEW_POSTHOG_KEY: string | undefined =",
    `  ${JSON.stringify(key)};`,
    "",
  ].join("\n"),
);
console.log(`embed-posthog-key: wrote key to ${target}`);
